def width(s, scale=1): return (sum(len(F[c][0]) + 1 for c in s) - 1) * scale
def text(px, s, x0, y0, color, scale=1, size=None):
    cx = 0
    for ch in s:
        g = F[ch]
        for j, row in enumerate(g):
            for i, c in enumerate(row):
                if c != '#': continue
                for a in range(scale):
                    for b in range(scale):
                        x, y = x0 + (cx + i) * scale + a, y0 + j * scale + b
                        if size is None or (0 <= x < size[0] and 0 <= y < size[1]): px[x, y] = color
        cx += len(g[0]) + 1
